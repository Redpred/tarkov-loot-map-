import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {LOOT_CATEGORIES,handbookLootFamily} from '../site/atlas-loot-category-policy.js';

const root=path.resolve(import.meta.dirname,'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8').replace(/^\uFEFF/,''));
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex');
const source=read('data/spt-source.json'),database=path.resolve(root,source.databasePath);
if(!database.startsWith(root+path.sep))throw new Error('Loot classification source must be inside the project');
const relativeFiles=['templates/items.json','templates/handbook.json'];
const inputs=relativeFiles.map(relative=>{
  const file=source.databasePath+'/'+relative,sha256=hash(file);
  if(source.files[relative]?.sha256!==sha256)throw new Error('Loot classification source hash mismatch: '+relative);
  return {file,sha256};
});
inputs.push({file:'site/atlas-loot-category-policy.js',sha256:hash('site/atlas-loot-category-policy.js')});
const templates=read(inputs[0].file),handbook=read(inputs[1].file);
const categories=new Map(handbook.Categories.map(c=>[c.Id,c]));
const itemCategories=new Map(handbook.Items.map(i=>[i.Id,i.ParentId]));
const groups=Object.fromEntries(Object.keys(LOOT_CATEGORIES).map(key=>[key,[]]));
for(const item of Object.values(templates).filter(item=>item._type==='Item').sort((a,b)=>a._id.localeCompare(b._id))){
  groups[handbookLootFamily(item._id,templates,categories,itemCategories)].push(item._id);
}
const provenance={schemaVersion:1,eftBuild:source.eftBuild,eftVersion:source.eftVersion,commit:source.commit,inputs};
const output='site/data/loot-categories.js';
const body='// Generated by scripts/build-loot-categories.mjs from the versioned project source.\n'
  +'export const LOOT_CATEGORY_SOURCE='+JSON.stringify(provenance)+';\n'
  +'const groups='+JSON.stringify(groups)+';\n'
  +'export const ITEM_LOOT_FAMILIES=Object.freeze(Object.fromEntries(Object.entries(groups).flatMap(([family,items])=>items.map(tpl=>[tpl,family]))));\n';
fs.writeFileSync(path.join(root,output),body);
console.log(JSON.stringify({output,bytes:Buffer.byteLength(body),items:Object.values(groups).reduce((n,items)=>n+items.length,0),groups:Object.fromEntries(Object.entries(groups).map(([key,items])=>[key,items.length]))},null,2));
